-- CONSULTA 01 - Participacoes em missoes (INNER JOIN)
SELECT
    P.NM_USUARIO,
    M.NM_MISSAO,
    PM.QTD_PONTOSGANHOS,
    PM.DS_STATUSPARTICIPACAO
FROM PESSOA P
INNER JOIN USUARIO U
    ON P.ID_PESSOA = U.PESSOA_ID_PESSOA
INNER JOIN PARTICIPACAO_MISSAO PM
    ON U.ID_USUARIO = PM.USUARIO_ID_USUARIO
INNER JOIN MISSAO M
    ON PM.MISSAO_ID_MISSAO = M.ID_MISSAO
ORDER BY PM.ID_PARTICIPACAO;

-- CONSULTA 02 - Todos os usuarios e suas missoes (LEFT JOIN)
SELECT
    P.NM_USUARIO,
    M.NM_MISSAO,
    PM.DS_STATUSPARTICIPACAO
FROM PESSOA P
INNER JOIN USUARIO U
    ON P.ID_PESSOA = U.PESSOA_ID_PESSOA
LEFT JOIN PARTICIPACAO_MISSAO PM
    ON U.ID_USUARIO = PM.USUARIO_ID_USUARIO
LEFT JOIN MISSAO M
    ON PM.MISSAO_ID_MISSAO = M.ID_MISSAO
ORDER BY P.ID_PESSOA, PM.ID_PARTICIPACAO;

-- CONSULTA 03 - Quantidade de participacoes por missao (RIGHT JOIN, GROUP BY e COUNT)
SELECT
    M.ID_MISSAO,
    M.NM_MISSAO,
    COUNT(PM.ID_PARTICIPACAO) AS TOTAL_PARTICIPACOES
FROM PARTICIPACAO_MISSAO PM
RIGHT JOIN MISSAO M
    ON PM.MISSAO_ID_MISSAO = M.ID_MISSAO
GROUP BY
    M.ID_MISSAO,
    M.NM_MISSAO
ORDER BY M.ID_MISSAO;

-- CONSULTA 04 - Total de pontos convertidos por usuario (SUM e GROUP BY)
SELECT
    P.NM_USUARIO,
    SUM(C.QTD_PONTOS_MOVIDOS) AS TOTAL_PONTOS_CONVERTIDOS
FROM PESSOA P
INNER JOIN USUARIO U
    ON P.ID_PESSOA = U.PESSOA_ID_PESSOA
INNER JOIN CONVERSAO C
    ON U.ID_USUARIO = C.USUARIO_ID_USUARIO
GROUP BY P.NM_USUARIO
ORDER BY TOTAL_PONTOS_CONVERTIDOS DESC;

-- CONSULTA 05 - Usuarios com pelo menos 60 pontos (WHERE)
SELECT
    P.NM_USUARIO,
    U.QTD_PONTOS,
    U.DS_STATUS
FROM PESSOA P
INNER JOIN USUARIO U
    ON P.ID_PESSOA = U.PESSOA_ID_PESSOA
WHERE U.QTD_PONTOS >= 60
ORDER BY U.QTD_PONTOS DESC;
